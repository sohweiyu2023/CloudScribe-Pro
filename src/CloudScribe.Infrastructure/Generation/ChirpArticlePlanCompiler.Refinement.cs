using System.Text.Json;
using CloudScribe.Application.Documents;
using CloudScribe.Application.Generation;
using CloudScribe.Domain.Generation;

namespace CloudScribe.Infrastructure.Generation;

public static partial class ChirpArticlePlanCompiler
{
    public const string RefinementVersion = "chirp3-one-failed-range-existing-clauses-v1";

    /// <summary>Pure proposal; full failed-attempt and accepted-output provenance remains a production admission prerequisite.</summary>
    public static ChirpArticlePlanProposal CompileRefined(DocumentSnapshot document, ChirpFailedPlanRefinement refinement,
        IReadOnlyList<ChirpNarrationReuse> verifiedReuse)
    {
        ArgumentNullException.ThrowIfNull(refinement); ArgumentNullException.ThrowIfNull(verifiedReuse);
        var parent = refinement.Parent;
        if (parent is null || parent.Refinement is not null || refinement.FailedAuthorizationId == Guid.Empty
            || !Guid.TryParseExact(refinement.FailedLocalAttemptId, "N", out _)
            || !ChirpPolicyValidation.IsHash(refinement.FailedAttemptRowSha256) || !ChirpPolicyValidation.IsHash(refinement.FailedQueueRowSha256))
            throw new InvalidOperationException("One exact original failed request is required; nested refinement is not authorized.");
        var originalReuse = parent.Parts.Where(x => x.Range.ReusedReceiptSha256 is not null)
            .Select(x => new ChirpNarrationReuse(x.Range.StartScalar, x.Range.EndScalarExclusive, x.Range.TextSha256, x.Range.ReusedReceiptSha256!)).ToArray();
        RequireCurrent(parent, document, originalReuse);
        if (verifiedReuse.Count > parent.Parts.Count || verifiedReuse.Select(x => (x.StartScalar, x.EndScalarExclusive)).Distinct().Count() != verifiedReuse.Count)
            throw new InvalidOperationException("Accepted parent coverage is duplicated or oversized.");
        foreach (var reuse in verifiedReuse)
        {
            if (!ChirpPolicyValidation.IsHash(reuse.ReceiptSha256) || parent.Parts.Count(x => x.Range.StartScalar == reuse.StartScalar
                && x.Range.EndScalarExclusive == reuse.EndScalarExclusive && string.Equals(x.Range.TextSha256, reuse.TextSha256, StringComparison.Ordinal)) != 1)
                throw new InvalidOperationException("Only exact whole accepted parent ranges can be reused.");
        }
        foreach (var original in originalReuse)
            if (!verifiedReuse.Contains(original)) throw new InvalidOperationException("Original accepted audio cannot be dropped.");
        var failed = parent.Parts.SingleOrDefault(x => x.CoverageOrdinal == refinement.FailedCoverageOrdinal)
            ?? throw new InvalidOperationException("The failed parent range is absent.");
        if (failed.Range.ReusedReceiptSha256 is not null || verifiedReuse.Any(x => x.StartScalar == failed.Range.StartScalar))
            throw new InvalidOperationException("Accepted coverage cannot be regenerated by refinement.");
        var subdivision = ChirpFailedRangeSubdivisionCompiler.Compile(document, parent, refinement.FailedCoverageOrdinal, originalReuse);
        List<ChirpArticlePlanPart> parts = [];
        foreach (var old in parent.Parts)
        {
            if (old.CoverageOrdinal == refinement.FailedCoverageOrdinal)
            {
                foreach (var smaller in subdivision.Parts) parts.Add(smaller with { CoverageOrdinal = parts.Count + 1 });
                continue;
            }
            var reuse = verifiedReuse.SingleOrDefault(x => x.StartScalar == old.Range.StartScalar && x.EndScalarExclusive == old.Range.EndScalarExclusive);
            parts.Add(reuse is null ? old with { CoverageOrdinal = parts.Count + 1 }
                : new(parts.Count + 1, old.Range with { ReusedReceiptSha256 = reuse.ReceiptSha256 }, null, 0));
        }
        _ = ChirpNarrationPlanner.SliceAll(document.Text, parts.Select(x => x.Range).ToArray());
        var proposal = parent with { PlannerVersion = RefinementVersion, PlanSha256 = string.Empty, Parts = parts.AsReadOnly(), Refinement = refinement };
        return proposal with { PlanSha256 = Hash(proposal) };
    }
}
