using Avalonia;
using Avalonia.Automation;
using Avalonia.Controls;
using Avalonia.Layout;
using Avalonia.Media;
using Avalonia.Platform.Storage;
using Avalonia.Styling;
using CloudScribe.App.Diagnostics;
using CloudScribe.App.ViewModels;
using CloudScribe.Application.Documents;

namespace CloudScribe.App.Composition;

public sealed partial class GoogleTtsUsabilityHotfixBinder
{
    private bool _articleDialogOpen;

    private async Task OpenArticleExportAsync(MainWindow owner, ShellViewModel model)
    {
        if (_articleDialogOpen) return;
        _articleDialogOpen = true;
        try
        {
            var articles = (await articleGroups.QueryLibraryAsync(string.Empty).ConfigureAwait(true))
                .Where(x => x.Parts.Count > 0).ToArray();
            Window dialog = CreateArticleExportDialog();
            using var lifetime = new CancellationTokenSource();
            dialog.Closed += (_, _) => lifetime.Cancel();
            Task? activeExport = null;
            StackPanel body = new() { Margin = new Thickness(20), Spacing = 14 };
            TextBlock description = CreateArticleExportDescription();
            ComboBox choice = new() { ItemsSource = articles.Select(x => x.Document.Title).ToArray(), HorizontalAlignment = HorizontalAlignment.Stretch };
            AutomationProperties.SetName(choice, "Original article for continuous MP3");
            TextBlock status = new() { Foreground = Brushes.White, TextWrapping = TextWrapping.Wrap };
            Button export = NewButton("Export complete article MP3");
            export.IsEnabled = false;
            var refreshSelection = BindArticleSelection(choice, export, status, articles, lifetime.Token);
            export.Click += (_, _) =>
            {
                if (!export.IsEnabled || choice.SelectedIndex < 0) return;
                Guid parentId = articles[choice.SelectedIndex].Document.Id;
                activeExport = RunArticleExportClickAsync(dialog, model, parentId, choice, export, status, lifetime.Token);
            };
            Button close = NewButton("Close");
            close.Click += (_, _) => dialog.Close();
            Button historical = NewButton("Review admitted historical audio…");
            historical.Click += async (_, _) =>
            {
                if (activeExport is { IsCompleted: false }) return;
                activeExport = RunArticleHistoricalImportAsync(dialog, model, historical, choice, refreshSelection, lifetime.Token);
                await activeExport.ConfigureAwait(true);
            };
            foreach (Control control in new Control[] { description, choice, status, export, historical, close }) body.Children.Add(control);
            status.Text = articles.Length == 0 ? "No prepared article groups. Prepare local parts first; no audio is generated by preparation." : "Choose an original article to check completeness.";
            dialog.Content = new ScrollViewer { Content = body };
            await dialog.ShowDialog(owner).ConfigureAwait(true);
            if (activeExport is not null) await activeExport.ConfigureAwait(true);
        }
        catch (Exception error) when (error is not OutOfMemoryException and not StackOverflowException and not AccessViolationException)
        { model.StatusMessage = "Article export is unavailable; local documents and audio were preserved."; }
        finally { _articleDialogOpen = false; }
    }
    private async Task RunArticleHistoricalImportAsync(Window dialog, ShellViewModel model, Button historical,
        ComboBox choice, Func<bool, Task> refreshSelection, CancellationToken cancellationToken)
    {
        historical.IsEnabled = false;
        choice.IsEnabled = false;
        await refreshSelection(true).ConfigureAwait(true);
        try { await OpenHistoricalAudioImportAsync(dialog, model, cancellationToken).ConfigureAwait(true); }
        finally
        {
            if (!cancellationToken.IsCancellationRequested)
            {
                await refreshSelection(false).ConfigureAwait(true);
                historical.IsEnabled = true;
                choice.IsEnabled = true;
            }
        }
    }

    private static TextBlock CreateArticleExportDescription() => new()
    {
        Text = "Join every verified local part into one continuous MP3 in article order. No synthesis or provider requests. Originals and financial records stay unchanged. Requires an existing FFmpeg installation with ffprobe.exe alongside it.",
        Foreground = Brushes.White,
        TextWrapping = TextWrapping.Wrap,
    };

    private Func<bool, Task> BindArticleSelection(ComboBox choice, Button export, TextBlock status,
        NarrationLibraryArticle[] articles, CancellationToken cancellationToken)
    {
        int version = 0;
        async Task RefreshAsync(bool blocked)
        {
            int observed = ++version;
            export.IsEnabled = false;
            if (blocked || cancellationToken.IsCancellationRequested || choice.SelectedIndex < 0) return;
            NarrationLibraryArticle article = articles[choice.SelectedIndex];
            try
            {
                var result = await InspectArticlePresentationAsync(article.Document.Id).ConfigureAwait(true);
                if (observed != version || cancellationToken.IsCancellationRequested) return;
                status.Text = result.Status;
                export.IsEnabled = result.Complete;
            }
            catch (Exception error) when (error is not OutOfMemoryException and not StackOverflowException and not AccessViolationException)
            { if (observed == version && !cancellationToken.IsCancellationRequested) status.Text = "Article text, grouping or local evidence needs review. No generation was started."; }
        }
        choice.SelectionChanged += async (_, _) => await RefreshAsync(false).ConfigureAwait(true);
        return RefreshAsync;
    }

    private static Window CreateArticleExportDialog() => new()
    {
        Title = "Export complete article MP3",
        Width = 620,
        Height = 480,
        WindowStartupLocation = WindowStartupLocation.CenterOwner,
        RequestedThemeVariant = ThemeVariant.Dark,
        Background = new SolidColorBrush(Color.Parse("#111C2B")),
    };

    private async Task<(bool Complete, string Status)> InspectArticlePresentationAsync(Guid parentId)
    {
        var inspected = await articleAudio.InspectAsync(parentId).ConfigureAwait(true);
        int available = inspected.Manifest.Members.Count(member => inspected.Audio.Count(x => x.DocumentId == member.DocumentId
            && x.RevisionId == member.RevisionId && string.Equals(x.TextSha256, member.TextSha256, StringComparison.Ordinal)) == 1);
        string status = $"{available}/{inspected.Manifest.Members.Count} parts have exact saved output provenance. Missing or uncertain parts block export. Earlier session-only MP3s require provenance review, never automatic regeneration.";
        try { inspected.Manifest.RequireComplete(inspected.Audio); return (true, status); }
        catch (InvalidOperationException) { return (false, status); }
    }

    private async Task RunArticleExportClickAsync(Window dialog, ShellViewModel model, Guid parentId,
        ComboBox choice, Button export, TextBlock status, CancellationToken cancellationToken)
    {
        export.IsEnabled = false;
        choice.IsEnabled = false;
        try { await ExecuteArticleExportAsync(dialog, model, parentId, status, cancellationToken).ConfigureAwait(true); }
        finally
        {
            if (!cancellationToken.IsCancellationRequested)
            {
                try { export.IsEnabled = (await InspectArticlePresentationAsync(parentId).ConfigureAwait(true)).Complete; }
                catch (Exception error) when (error is not OutOfMemoryException and not StackOverflowException and not AccessViolationException)
                { status.Text = "Article evidence changed; review it before exporting."; }
            }
            choice.IsEnabled = true;
        }
    }

    private async Task ExecuteArticleExportAsync(Window dialog, ShellViewModel model, Guid parentId, TextBlock status, CancellationToken cancellationToken)
    {
        try
        {
            NativeUiDiagnosticLog.Action(NativeUiOperation.Export, NativeUiPhase.Open);
            var tools = await dialog.StorageProvider.OpenFilePickerAsync(new()
            {
                Title = "Select installed ffmpeg.exe (with ffprobe.exe alongside)",
                AllowMultiple = false,
                FileTypeFilter = [new FilePickerFileType("FFmpeg executable") { Patterns = ["ffmpeg.exe"] }],
            }).ConfigureAwait(true);
            cancellationToken.ThrowIfCancellationRequested();
            if (tools.Count != 1 || !tools[0].Path.IsFile) { status.Text = "Article export cancelled; originals unchanged."; return; }
            var destination = await dialog.StorageProvider.SaveFilePickerAsync(new()
            {
                Title = "Save one continuous article MP3 to a new file",
                SuggestedFileName = "complete-article.mp3",
                DefaultExtension = "mp3",
                FileTypeChoices = [Mp3FileType],
                ShowOverwritePrompt = true,
            }).ConfigureAwait(true);
            cancellationToken.ThrowIfCancellationRequested();
            if (destination is null || !destination.Path.IsFile) { status.Text = "Article export cancelled; originals unchanged."; return; }
            status.Text = "Verifying and joining complete local audio. No provider call will be made.";
            await articleAudio.ExportAsync(parentId, destination.Path.LocalPath, tools[0].Path.LocalPath, cancellationToken).ConfigureAwait(true);
            NativeUiDiagnosticLog.Action(NativeUiOperation.Export, NativeUiPhase.Complete);
            status.Text = "One continuous article MP3 exported and locally decoded successfully. Originals preserved.";
            model.StatusMessage = status.Text;
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            NativeUiDiagnosticLog.Action(NativeUiOperation.Export, NativeUiPhase.Cancel);
            status.Text = "Article export cancelled; originals unchanged.";
        }
        catch (Exception error) when (error is not OutOfMemoryException and not StackOverflowException and not AccessViolationException)
        {
            NativeUiDiagnosticLog.Action(NativeUiOperation.Export, NativeUiPhase.Failed, error);
            status.Text = "Article export stopped safely. Check complete revision evidence, local audio integrity, FFmpeg and a new writable filename. No synthesis or ledger change was made.";
        }

    }

}
